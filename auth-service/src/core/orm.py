from datetime import datetime
from typing import Any
from uuid import UUID as PyUUID

from sqlalchemy import (
    BIGINT,
    INTEGER,
    TIMESTAMP,
    Boolean,
    DateTime,
    MetaData,
    String,
    false,
    func,
)
from sqlalchemy.dialects.postgresql import ARRAY, JSONB, UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

metadata_obj = MetaData(
    naming_convention={
        "ix": "ix_%(column_0_label)s",
        "uq": "uq_%(table_name)s_%(column_0_name)s",
        "ck": "ck_%(table_name)s_%(constraint_name)s",
        "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
        "pk": "pk_%(table_name)s",
    }
)


class Base(DeclarativeBase):
    """Declarative base carrying the shared naming convention.

    The explicit convention means constraint and index names are generated
    identically in every service, so Alembic autogenerate produces stable
    names instead of database-assigned ones.
    """

    __abstract__ = True

    metadata = metadata_obj

    type_annotation_map = {
        int: BIGINT,
        datetime: TIMESTAMP(timezone=False),
        str: String(),
        dict[str, Any]: JSONB,
        list[PyUUID]: ARRAY(UUID(as_uuid=True)),
        list[str]: ARRAY(String()),
        list[int]: ARRAY(INTEGER),
    }


class CreatedAtMixin:
    """Adds a creation timestamp generated by the database.

    Use on append-only tables that never record a modification time.
    """

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
        comment="Дата создания записи",
    )


class TimestampMixin(CreatedAtMixin):
    """Adds creation and modification timestamps generated by the database.

    Both values come from the server clock rather than the application's, so
    rows written by migrations, seeds, or raw SQL are stamped consistently.
    """

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
        comment="Дата последнего обновления записи",
    )


class SoftDeleteMixin:
    """Flags rows as deleted instead of removing them.

    Applied to entity tables only — append-only audit logs and pure
    association tables are excluded, since neither is ever deleted by row.
    Reads must filter this column; BaseRepository does so automatically.
    """

    is_delete: Mapped[bool] = mapped_column(
        Boolean,
        server_default=false(),
        nullable=False,
        index=True,
        comment="Признак мягкого удаления записи",
    )
